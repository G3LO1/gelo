#!/usr/bin/env python3
"""Builds the gelo LLM pack (llm/dist) from the skills, for ChatGPT, Gemini, Claude Projects and any other model.

    python3 llm/build.py           # write llm/dist
    python3 llm/build.py --check   # fail if llm/dist is out of date (CI)

Output:
    dist/gelo-instructions.md   system prompt / Custom GPT instructions (kept under 8,000 characters)
    dist/knowledge/<skill>.md   one file per skill: SKILL.md + its references, list of scripts and assets
    dist/gelo-full.md           instructions + every knowledge file, to paste into one prompt
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SKILLS = ROOT / "plugins" / "roblox-studio" / "skills"
HERE = ROOT / "llm"
DIST = HERE / "dist"
REPO = "https://github.com/G3LO1/gelo"
TREE = f"{REPO}/tree/main/plugins/roblox-studio/skills"
ROUTER = "gelo"
# Custom GPT instructions are capped at 8,000 characters; stay below with room for edits.
INSTRUCTIONS_LIMIT = 8000

FRONTMATTER = re.compile(r"\A---\n(.*?)\n---\n", re.S)
ROUTES = re.compile(r"<!-- gelo:routes:start -->\n(.*?)\n<!-- gelo:routes:end -->", re.S)


def split_skill(path: Path) -> tuple[dict[str, str], str]:
    text = path.read_text(encoding="utf-8")
    m = FRONTMATTER.match(text)
    if not m:
        raise SystemExit(f"{path}: no frontmatter")
    meta = {}
    for line in m.group(1).splitlines():
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip().strip('"')
    return meta, text[m.end():].strip() + "\n"


def skill_dirs() -> list[Path]:
    return sorted(d for d in SKILLS.iterdir() if (d / "SKILL.md").is_file())


def knowledge_file(skill: Path) -> str:
    meta, body = split_skill(skill / "SKILL.md")
    name = meta["name"]
    if name != skill.name:
        raise SystemExit(f"{skill}: frontmatter name {name!r} differs from folder")
    out = [
        f"<!-- Generated by llm/build.py from plugins/roblox-studio/skills/{name}. Do not edit. -->",
        f"# Skill: {name}",
        "",
        f"**When to use:** {meta['description']}",
        "",
        f"Skill folder (scripts, assets): {TREE}/{name}",
        "",
        "## File: SKILL.md",
        "",
        body,
    ]
    refs = sorted((skill / "references").glob("*.md")) if (skill / "references").is_dir() else []
    for ref in refs:
        out += [f"## File: references/{ref.name}", "", ref.read_text(encoding="utf-8").strip() + "\n"]
    included = {skill / "SKILL.md", *refs}
    other = sorted(p.relative_to(skill).as_posix() for p in skill.rglob("*") if p.is_file() and p not in included)
    if other:
        out += [
            "## Files not included here",
            "",
            f"Scripts and assets of this skill. Download them from {TREE}/{name} (paths relative to that folder):",
            "",
            *[f"- `{p}`" for p in other],
            "",
        ]
    return "\n".join(out)


def instructions() -> str:
    _, router_body = split_skill(SKILLS / ROUTER / "SKILL.md")
    m = ROUTES.search(router_body)
    if not m:
        raise SystemExit(f"{ROUTER}/SKILL.md: routes markers not found")
    # In the pack each skill is a knowledge file, so name the file.
    routes = re.sub(r"`(roblox-[a-z0-9-]+)`", r"`\1.md`", m.group(1).strip())
    template = (HERE / "instructions.template.md").read_text(encoding="utf-8")
    text = template.replace("{{ROUTES}}", routes).replace("{{REPO}}", REPO)
    if "{{" in text:
        raise SystemExit("instructions.template.md: unknown placeholder")
    return text


def build() -> dict[Path, str]:
    files: dict[Path, str] = {}
    instr = instructions()
    if len(instr) > INSTRUCTIONS_LIMIT:
        raise SystemExit(f"gelo-instructions.md is {len(instr)} characters, limit {INSTRUCTIONS_LIMIT}")
    files[DIST / "gelo-instructions.md"] = instr
    knowledge = []
    for skill in skill_dirs():
        if skill.name == ROUTER:
            continue
        text = knowledge_file(skill)
        files[DIST / "knowledge" / f"{skill.name}.md"] = text
        knowledge.append(text)
    routed = set(re.findall(r"`(roblox-[a-z0-9-]+)\.md`", instr))
    have = {p.stem for p in files if p.parent.name == "knowledge"}
    if routed != have:
        raise SystemExit(f"routes and skills differ: only routed {sorted(routed - have)}, not routed {sorted(have - routed)}")
    files[DIST / "gelo-full.md"] = "\n\n---\n\n".join(
        [instr, "# Knowledge files\n\nEach section below is one knowledge file (`<skill>.md`)."] + knowledge
    )
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if llm/dist is out of date")
    args = ap.parse_args()
    files = build()
    existing = {p for p in DIST.rglob("*") if p.is_file()} if DIST.exists() else set()
    if args.check:
        stale = [p for p, text in files.items() if not p.is_file() or p.read_text(encoding="utf-8") != text]
        extra = existing - set(files)
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}", file=sys.stderr)
        for p in sorted(extra):
            print(f"not generated: {p.relative_to(ROOT)}", file=sys.stderr)
        if stale or extra:
            print("Run: python3 llm/build.py", file=sys.stderr)
            return 1
        print(f"OK: llm/dist up to date ({len(files)} files, instructions {len(files[DIST / 'gelo-instructions.md'])} chars)")
        return 0
    for p in existing - set(files):
        p.unlink()
    for p, text in files.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    print(f"Wrote {len(files)} files to {DIST.relative_to(ROOT)} (instructions {len(files[DIST / 'gelo-instructions.md'])} chars)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
